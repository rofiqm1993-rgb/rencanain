import { build } from "esbuild";
import assert from "node:assert/strict";
import { mkdir, readFile } from "node:fs/promises";
await mkdir("outputs", { recursive: true });
await build({ stdin: { contents: 'export * from "./lib/prd.ts"; export * from "./lib/tech-stack.ts"; export * from "./lib/clarification.ts"; export * from "./lib/design-standards.ts";', resolveDir: process.cwd() }, bundle: true, platform: "node", format: "esm", outfile: "outputs/planning-test-module.mjs" });
const { newDraft, readDraft, clarificationQuestions, hasMonetizationIntent, normalizePRD, examplePRD, prdSchema, taskList, exportMarkdown, assessPRD, stackConflicts, alignStack, recommendStack, DESIGN_STANDARD } = await import("../outputs/planning-test-module.mjs");
const draft = { ...newDraft("Aplikasi keuangan rumah tangga untuk mencatat pengeluaran dan menjaga anggaran keluarga."), completed: true, step: 4, answers: [["Keluarga"], ["Ringkasan data"], ["Catat pengeluaran", "Atur anggaran", "Atur kategori transaksi"], ["Nyaman di ponsel"], []] };
const fallback = examplePRD(draft);
assert(prdSchema.safeParse(fallback).success);
const raw = structuredClone(fallback);
raw.phases.forEach(p => { p.id = "duplicate"; p.features.forEach(f => { f.id = "duplicate"; f.title = "Fitur tambahan"; f.subfeatures.forEach(t => { t.id = "duplicate"; }); }); });
raw.dataModel[0].fields = Array.from({ length: 20 }, (_, i) => `field_${i}: string`);
delete raw.risks;
const normalized = normalizePRD(raw, draft);
assert(prdSchema.safeParse(normalized.prd).success);
for (const title of [...draft.answers[2], "Pembukaan pertama: Ringkasan data"]) assert(normalized.prd.phases[0].features.some(f => f.title === title));
assert.equal(normalized.prd.phases[0].features.length, 4);
const tasks = taskList(normalized.prd);
assert.equal(new Set(tasks.map(t => t.id)).size, tasks.length);
assert(normalized.prd.dataModel[0].fields.some(f => f.startsWith("household_id")));
assert(normalized.normalized.includes("risks"));
assert(normalized.normalized.includes("household_id"));
const mismatchedOpening = structuredClone(fallback);
mismatchedOpening.phases[0].features[3].title = "Pembukaan pertama: judul model berbeda";
mismatchedOpening.phases[0].features[3].description = "Isi onboarding spesifik yang dibuat model.";
const repairedOpening = normalizePRD(mismatchedOpening, draft);
assert.equal(repairedOpening.prd.phases[0].features.filter(f => f.title.startsWith("Pembukaan pertama:")).length, 1);
assert.equal(repairedOpening.prd.phases[0].features[3].description, "Isi onboarding spesifik yang dibuat model.");
assert(prdSchema.safeParse(normalizePRD({}, draft).prd).success);
const stack = recommendStack(draft).stack;
const conflict = { ...stack, database: "PostgreSQL" };
assert(stackConflicts(conflict).length > 0);
assert.equal(conflict.database, "PostgreSQL");
assert.equal(stackConflicts(alignStack(conflict)).length, 0);
const plan = { prd: normalized.prd, source: "ai", model: "test-model", normalized: normalized.normalized, draft, stack, generatedAt: "2026-10-03T00:00:00Z" };
const markdown = exportMarkdown(plan, { [tasks[0].id]: true });
for (const content of ["household_id", "## Risiko", "## Asumsi", "## Lampiran", draft.idea, "[x]", "DeepSeek (test-model)", "Normalisasi lokal"]) assert(markdown.includes(content));
const paidIdea = "Aplikasi SaaS Next.js dengan Firebase Auth, Firestore, paket Free dan Pro serta Midtrans Snap untuk pembayaran langganan.";
const oldPaidDraft = newDraft(paidIdea);
const migrated = readDraft(JSON.stringify({ ...oldPaidDraft, step: 4, completed: true }));
assert.equal(migrated?.completed, false);
assert.equal(migrated?.step, 5);
const paidDraft = { ...oldPaidDraft, completed: true, step: 7, monetization: { entitlements: ["Free: 2 PRD; Pro: 20 PRD"], quota: ["Kuota reset tiap bulan"], paymentFailure: ["Tetap Free jika pembayaran gagal"] } };
assert(hasMonetizationIntent(paidDraft));
assert.equal(clarificationQuestions(paidDraft).length, 8);
assert.equal(clarificationQuestions(draft).length, 5);
const staleExtra = readDraft(JSON.stringify({ ...newDraft("Aplikasi inventori untuk toko kecil agar stok dan transaksi harian mudah dicatat."), monetization: paidDraft.monetization }));
assert.equal(staleExtra?.monetization, undefined);
const soloDraft = { ...newDraft("Aplikasi catatan pribadi untuk seorang pengguna yang ingin menyimpan jurnal hariannya sendiri."), completed: true, step: 4 };
assert(!examplePRD(soloDraft).dataModel[0].fields.some(value => value.startsWith("household_id")));
const paidStack = recommendStack(paidDraft).stack;
assert.deepEqual(paidStack, { frontend: "Next.js", backend: "Next.js API routes", database: "Firestore", deployment: "Vercel" });
const paymentWithoutServer = { frontend: "React + Vite", backend: "Firebase", database: "Firestore", deployment: "Firebase Hosting" };
assert(stackConflicts(paymentWithoutServer, paidDraft).length > 0);
assert.equal(stackConflicts(alignStack(paymentWithoutServer, paidDraft), paidDraft).length, 0);
const paidPRD = examplePRD(paidDraft, paidStack);
assert(paidPRD.technicalArchitecture.paymentNotifications.some(value => value.includes("idempoten")));
assert(paidPRD.technicalArchitecture.identityAndData.some(value => value.includes("Firestore Rules")));
assert.deepEqual(paidPRD.permissionMatrix.map(value => value.role), ["Free", "Pro"]);
assert(paidPRD.systemAcceptance.some(value => value.action.includes("dua kali")));
assert(paidPRD.systemAcceptance.some(value => value.precondition.includes("kuota")));
const paidPlan = { ...plan, prd: paidPRD, draft: paidDraft, stack: paidStack };
const paidMarkdown = exportMarkdown(paidPlan);
for (const content of ["## Aturan monetisasi", "Free: 2 PRD", "## User Flow", "## Matriks izin dan peran", "## Sistem desain (design.md)", "#2789D8", "375px", "## Arsitektur teknis", "## Aturan akses data Firestore", "Firebase Auth", "Firestore Rules", "Midtrans Snap", "signature_key", "order_id", "callback browser", "## Kriteria penerimaan sistem", "**Kondisi awal:**", "**Tindakan:**", "**Hasil teramati:**", "## Keputusan terbuka (Unresolved Decisions)"]) assert(paidMarkdown.includes(content), content);
assert.equal(assessPRD(paidPlan).readyForTechnicalReview, false);
const legacyPRD = structuredClone(fallback);
delete legacyPRD.userFlows;
delete legacyPRD.permissionMatrix;
delete legacyPRD.systemAcceptance;
delete legacyPRD.unresolvedDecisions;
legacyPRD.phases[0].features[0].acceptance = ["Kriteria lama yang belum dipecah menjadi skenario."];
const migratedPRD = prdSchema.parse(legacyPRD);
assert.equal(migratedPRD.phases[0].features[0].acceptance[0].precondition, "Belum dirinci pada PRD lama.");
assert.equal(migratedPRD.userFlows.length, 0);
const repairedPaid = normalizePRD({ ...paidPRD, userFlows: [], permissionMatrix: [], systemAcceptance: [] }, paidDraft, paidStack).prd;
assert.deepEqual(repairedPaid.permissionMatrix.map(value => value.role), ["Free", "Pro"]);
assert(repairedPaid.systemAcceptance.some(value => value.action.includes("dua kali")));
const designFile = await readFile("design.md", "utf8");
for (const [key, value] of Object.entries(DESIGN_STANDARD.colors)) {
  const sourceKey = key.replace(/[A-Z]/g, letter => `-${letter.toLowerCase()}`);
  assert(designFile.includes(`${sourceKey}: "${value}"`), `design.md token ${sourceKey}`);
}
console.log("PASS: dynamic monetization questions; Firestore/Midtrans stack; mandatory MVP; legacy PRD migration; structured acceptance and quality gate; complete Markdown export; design token sync.");
